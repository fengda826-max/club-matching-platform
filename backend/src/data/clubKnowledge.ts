/**
 * 展开为扁平的知识块列表（供索引脚本 / 启动自建索引使用）。
 * 只保留在 `clubsByName` 中能找到的社团，附上其 clubId。
 */
export function flattenKnowledge(clubsByName: Map<string, number>): Array<{ clubId: number; section: string; content: string }> {
  const docs: Array<{ clubId: number; section: string; content: string }> = []
  for (const [name, sections] of Object.entries(clubKnowledge)) {
    const clubId = clubsByName.get(name)
    if (clubId === undefined) continue
    for (const { section, content } of sections) {
      // 把社团名拼进被 embed 的文本，让“摄影协会”这类名字也参与语义匹配
      docs.push({ clubId, section, content: `【${name} · ${section}】${content}` })
    }
  }
  return docs
}
